    <h1>Refund & Cancellation Policy</h1>
    <p class="date">Effective Date: 04 September 2026</p>

    <p>
        This policy applies to payments made for Centralized Mess services
        through mess.bilalkhawaja.pk and its associated member application.
    </p>

    <h2>Service Delivery &amp; Returns</h2>
    <p>
        Centralized Mess is a digital mess-management and billing service. No
        physical goods are shipped or delivered. Access to the service is
        provided electronically to registered members through the member
        application and the website immediately upon successful login.
    </p>
    <p>
        As this is a digital service, product returns do not apply. Any
        payment-related concern &mdash; including overpayment, duplicate
        payment, incorrect billing, or cancellation &mdash; is handled under
        the relevant sections of this policy below.
    </p>

    <h2>1. Refund Eligibility</h2>
    <p>A refund may be requested in cases including:</p>
    <ul>
        <li>Duplicate payment</li>
        <li>Verified overpayment</li>
        <li>Incorrect payment amount</li>
        <li>Payment charged against an incorrect mess billing record</li>
        <li>Other verified billing errors approved by the administration</li>
    </ul>

    <h2>2. Refund Request</h2>
    <p>
        Refund requests should be submitted to
        <a href="mailto:admin@nodesky.pk">admin@nodesky.pk</a>.
    </p>

    <p>Please provide, where applicable:</p>
    <ul>
        <li>Member name and Member ID</li>
        <li>Payment date</li>
        <li>Payment amount</li>
        <li>Transaction/reference number</li>
        <li>Reason for the refund request</li>
        <li>Supporting payment evidence or receipt</li>
    </ul>

    <h2>3. Processing Time</h2>
    <p>
        Approved refunds for verified overpayments or billing errors will
        normally be processed within 7 business days after verification.
        Additional time may be required by the relevant bank or payment
        service provider for the refunded amount to appear in the customer's account.
    </p>

    <h2>4. Refund Method</h2>
    <p>
        Where technically possible, refunds will be returned through the
        original payment method. Where this is not possible, the administration
        may arrange an alternative verified refund method.
    </p>

    <h2>5. Cancellation Policy</h2>
    <p>
        Centralized Mess payments generally relate to existing mess bills or
        charges. Once a payment has been successfully processed, the payment
        itself cannot normally be cancelled.
    </p>

    <p>
        If a payment was made in error, duplicated, or relates to an incorrect
        billing record, the member may submit a refund request under this policy.
    </p>

    <h2>6. Billing Disputes</h2>
    <p>
        Members should report billing discrepancies within 30 days of the
        relevant bill or payment so that the matter can be reviewed against
        available billing and transaction records.
    </p>

